/** 取字典文本并做 {var} 插值。lang 非法时回退 cmn。 */
export function t(lang, key, vars) {
    const dict = DICT[lang] || DICT.cmn;
    let s = dict[key];
    if (s === undefined) s = (DICT.cmn[key] !== undefined ? DICT.cmn[key] : key);
    if (vars && typeof s === 'string') {
        s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
    }
    return s;
}

/** 某 key 在指定语言下是否存在（用于帮助元数据回退判断）。 */
export function hasKey(lang, key) {
    return !!(DICT[lang] && DICT[lang][key] !== undefined);
}

export { LANGS, DICT };
export default { t, hasKey, LANGS, DICT };
